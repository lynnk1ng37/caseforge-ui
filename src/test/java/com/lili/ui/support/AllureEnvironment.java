package com.lili.ui.support;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.lili.ui.config.TestConfig;

import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.OffsetDateTime;
import java.time.format.DateTimeFormatter;
import java.util.LinkedHashMap;
import java.util.Map;
import java.util.Properties;

/**
 * 把「这次跑的是哪个环境、哪个分支、哪次构建」写进 allure-results。
 *
 * <p>为什么必须做：Allure 前端会把 {@code environment.properties} 渲染在报告首页，
 * 把 {@code executor.json} 渲染成右上角的构建信息。缺了这两份文件，把多个
 * Jenkins job 的 results 合并成一份报告后，就分不清每条失败属于哪个构建、哪套环境。
 *
 * <p>两者都在测试启动期写一次，失败了不影响用例结论。
 */
public final class AllureEnvironment {

    private AllureEnvironment() {
    }

    public static void write() {
        try {
            Path dir = resultsDir();
            Files.createDirectories(dir);
            writeEnvironment(dir.resolve("environment.properties"));
            writeExecutor(dir.resolve("executor.json"));
        } catch (Exception ignored) {
            // 元信息落盘失败不得影响用例结论
        }
    }

    /**
     * 结果目录与 allure-cucumber7 插件保持一致。
     *
     * <p>优先读插件自己的系统属性（{@code -Dallure.results.directory=...}，
     * pom 的 surefire 已钉到 {@code target/allure-results}）；IDE 里单跑 feature
     * 不走 surefire 时回落到 allure-java 的默认值 {@code allure-results}，
     * 保证元信息不会落到与结果文件不同的目录。
     */
    private static Path resultsDir() {
        String configured = System.getProperty("allure.results.directory");
        if (configured == null || configured.isBlank()) {
            configured = System.getenv("ALLURE_RESULTS_DIR");
        }
        if (configured == null || configured.isBlank()) {
            configured = "allure-results";
        }
        return Paths.get(configured.trim());
    }

    private static void writeEnvironment(Path target) throws Exception {
        Map<String, String> values = new LinkedHashMap<>();
        values.put("ui.env", TestConfig.get().envName());
        values.put("ui.base_url", TestConfig.get().baseUrl());
        values.put("ui.api_base_url", TestConfig.get().apiBaseUrl());
        String channel = TestConfig.get().channel();
        values.put("ui.browser", (channel == null ? "bundled-chromium" : channel) + " / "
                + (TestConfig.get().headless() ? "headless" : "headed"));
        values.put("ui.viewport", TestConfig.get().viewportWidth() + "x" + TestConfig.get().viewportHeight());
        values.put("ui.timeout_ms", String.valueOf((long) TestConfig.get().timeoutMs()));
        values.put("ci.job", env("JOB_NAME", "local"));
        values.put("ci.build", env("BUILD_NUMBER", "-"));
        values.put("ci.branch", env("GIT_BRANCH", env("GIT_LOCAL_BRANCH", "local")));
        values.put("ci.commit", env("GIT_COMMIT", "unknown"));
        values.put("runtime.java", System.getProperty("java.version", "unknown"));
        values.put("runtime.os", System.getProperty("os.name", "unknown"));

        // Properties.store 会把非 ASCII 转成 \\uXXXX 转义；
        // environment.properties 在 Allure 侧按 ISO-8859-1 解析，这样才不会乱码。
        Properties properties = new Properties();
        properties.putAll(values);
        try (OutputStream out = Files.newOutputStream(target)) {
            properties.store(out, "generated by AllureEnvironment");
        }
    }

    private static void writeExecutor(Path target) throws Exception {
        String buildUrl = env("BUILD_URL", "");
        boolean onCi = !buildUrl.isBlank();

        Map<String, Object> body = new LinkedHashMap<>();
        body.put("name", onCi ? env("JOB_NAME", "jenkins") : "local");
        body.put("type", onCi ? "jenkins" : "generic");
        body.put("url", onCi ? env("JENKINS_URL", "") : "");
        body.put("buildName", onCi
                ? "#" + env("BUILD_NUMBER", "0")
                : "local-" + OffsetDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd-HHmm")));
        body.put("buildUrl", buildUrl);
        body.put("reportName", "UI 回归");

        String json = new ObjectMapper().writeValueAsString(body);
        Files.writeString(target, json, StandardCharsets.UTF_8);
    }

    private static String env(String key, String fallback) {
        String value = System.getenv(key);
        return (value == null || value.isBlank()) ? fallback : value.trim();
    }
}
